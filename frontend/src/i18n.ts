export type Strings = typeof en;
type Key = { [K in keyof Strings]: Strings[K] extends string ? K : never }[keyof Strings];

export function strings(language: string): Strings {
  return language.startsWith("fr") ? fr : en;
}

export function t(lang: string, key: Key, vars: Record<string, string> = {}): string {
  let text = strings(lang)[key] as string;
  for (const [name, value] of Object.entries(vars)) text = text.replace(`{${name}}`, value);
  return text;
}

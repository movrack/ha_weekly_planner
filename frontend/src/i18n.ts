export type Strings = typeof en;
type Key = { [K in keyof Strings]: Strings[K] extends string ? K : never }[keyof Strings];

export function strings(language: string): Strings {
  return language.startsWith("fr") ? fr : en;
}

export function t(lang: string, key: Key, vars: Record<string, string> = {}): string {
  let text = strings(lang)[key] as string;
  for (const [name, value] of Object.entries(vars)) text = text.replace(`{${name}}`, value);
  return text;
}

/**
 * Text of a refused save about slot devices (#34 codes), or null when the message is about something else.
 * `overlapping_slots:<entity_id>` names the device; a bare `overlapping_slots` stays generic.
 */
export function slotDeviceError(lang: string, message: string | undefined, name: (entityId: string) => string): string | null {
  if (!message) return null;
  if (message.includes("empty_slot_entities")) return t(lang, "err_slot_entities");
  if (message.includes("duplicate_slot_entity")) return t(lang, "err_slot_duplicate");
  if (message.includes("unknown_slot_entity")) return t(lang, "err_slot_unknown");
  const eid = /overlapping_slots:([a-z0-9_]+\.[a-z0-9_]+)/.exec(message)?.[1];
  return eid ? t(lang, "err_overlap_device", { name: name(eid) }) : null;
}

/** Technical messages (service or command missing, connection, internal error) that a person cannot act on. */
const TECHNICAL = /unknown[_ ]command|not[_ ]found|not[_ ]loaded|unavailable|service|timeout|timed out|connection|disconnect|failed to fetch|socket|internal|traceback|exception|unknown_error|home_assistant_error/i;

/** What to show for a failed call: a plain sentence for technical failures (the detail goes to the console), else the message. */
export function errorText(lang: string, err: unknown): string {
  const message = (err as { message?: string } | null)?.message ?? String(err);
  if (TECHNICAL.test(message) || TECHNICAL.test((err as { code?: string } | null)?.code ?? "")) {
    if (typeof console !== "undefined") console.warn("weekly_planner:", message);
    return t(lang, "err_service");
  }
  return t(lang, "error", { message });
}
